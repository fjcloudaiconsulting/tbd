#!/usr/bin/env python3
"""Generate infra/ansible/inventory.yml from Terraform outputs (TBD-206/TBD-207).

WHY THIS EXISTS. `inventory.yml` is gitignored and was always hand-copied from
inventory.yml.example and filled in by eye -- outputs.tf even documents
vpc_ip_range as "echoed for convenience in Ansible inventory generation", but
the generation step was never built. The consequence showed up on 2026-08-18:
the file was simply absent, with no way to reconstruct it, and the data plane
could not be configured at all. Hosts are not the hard part; the point is that
the inventory must be DERIVABLE, so losing a laptop is not an outage.

⚠ THIS FILE DELIBERATELY EMITS NO SECRETS. Passwords are supplied at run time by
bin/run-playbook.sh, which reads them from Terraform outputs into a mode-0600
temp file and shreds it afterwards. Writing them into inventory.yml would put
plaintext credentials at rest on every operator laptop forever, which is the
habit that produced the CHANGE_ME footgun in the first place.

Usage:
  bin/gen-inventory.py                          # write inventory.yml from TF state
  bin/gen-inventory.py --stdout                 # print, change nothing
  bin/gen-inventory.py --host 1.2.3.4 --name scratch
        # point at a throwaway droplet so the play can be rehearsed off production
"""
import argparse
import json
import pathlib
import subprocess
import sys

ANSIBLE_DIR = pathlib.Path(__file__).resolve().parent.parent
TERRAFORM_DIR = ANSIBLE_DIR.parent / "terraform"

# Non-secret facts that belong to the inventory rather than to role defaults.
# Kept explicit so a new output does not silently become an inventory var.
REQUIRED_OUTPUTS = ("droplet_public_ipv4", "droplet_private_ipv4", "vpc_ip_range")


def terraform_outputs() -> dict:
    """Read TFC state. Requires `terraform login` (or TF_TOKEN_*) to be set up."""
    try:
        proc = subprocess.run(
            ["terraform", f"-chdir={TERRAFORM_DIR}", "output", "-json"],
            capture_output=True, text=True, timeout=120, check=False,
        )
    except FileNotFoundError:
        sys.exit("!! terraform not on PATH")
    except subprocess.TimeoutExpired:
        sys.exit("!! terraform output timed out (TFC unreachable?)")
    if proc.returncode != 0:
        sys.exit(f"!! terraform output failed:\n{proc.stderr.strip()}")
    try:
        raw = json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        sys.exit(f"!! terraform output was not JSON: {exc}")
    return {k: v.get("value") for k, v in raw.items()}


def build(outputs: dict, host: str | None, name: str) -> str:
    missing = [k for k in REQUIRED_OUTPUTS if not outputs.get(k)]
    # Fail loudly. A half-populated inventory is worse than none: it resolves,
    # runs, and targets the wrong or a nonexistent address.
    if missing and not host:
        sys.exit(f"!! terraform outputs missing: {', '.join(missing)}")

    public = host or outputs["droplet_public_ipv4"]
    private = outputs.get("droplet_private_ipv4", "")
    vpc = outputs.get("vpc_ip_range", "")

    lines = [
        "# GENERATED by infra/ansible/bin/gen-inventory.py -- do not hand-edit.",
        "# Source of truth is Terraform state (TFC workspace FlamaCorp/tbd).",
        "# Regenerate:  bin/gen-inventory.py",
        "#",
        "# Contains NO secrets by design. bin/run-playbook.sh injects those from",
        "# Terraform outputs at run time.",
        "all:",
        "  hosts:",
        f"    {name}:",
        f"      ansible_host: {public}",
        "      ansible_user: root",
        "      ansible_python_interpreter: /usr/bin/python3",
    ]
    if private:
        lines.append(f"      private_ipv4: {private}")
    lines.append("  vars:")
    if vpc:
        lines.append(f"    vpc_ip_range: {vpc}")
    # Names, not secrets. These match roles/*/defaults and are safe in plain text.
    lines += [
        "    mysql_app_db: pfv2",
        "    mysql_app_user: pfv_app",
        "    mysql_backup_user: pfv_backup",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true", help="print instead of writing")
    ap.add_argument("--host", help="override the target address (scratch droplet)")
    ap.add_argument("--name", default="pfv-data-01", help="inventory host name")
    ap.add_argument("--out", default=str(ANSIBLE_DIR / "inventory.yml"))
    args = ap.parse_args()

    # --host is for rehearsing against a throwaway box, so do not consult TFC
    # for an address we are about to override anyway.
    outputs = {} if args.host else terraform_outputs()
    content = build(outputs, args.host, args.name)

    if args.stdout:
        sys.stdout.write(content)
        return
    pathlib.Path(args.out).write_text(content)
    print(f"wrote {args.out}  (host={args.name})")


if __name__ == "__main__":
    main()
